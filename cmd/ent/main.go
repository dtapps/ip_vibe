func run_ent() {

	target := "./ent"
	target = "./internal/ent"
	// target = "./internal/ent_log"
	schemaPath := target + "/schema"
	outputHookDir := filepath.Join(target, "schema/schemahook")

	fmt.Println("target", target)
	fmt.Println("schemaPath", schemaPath)

	// 1. 配置生成参数
	cfg := &gen.Config{
		Target: target,
		Features: []gen.Feature{
			// gen.FeatureSnapshot,
			// gen.FeaturePrivacy,
			// gen.FeatureEntQL,
			gen.FeatureNamedEdges,
			gen.FeatureBidiEdgeRefs,
			// gen.FeatureSchemaConfig,
			// gen.FeatureLock,
			gen.FeatureModifier,
			gen.FeatureExecQuery,
			gen.FeatureUpsert,
		},
	}

	// 加载 Graph (这是你代码里缺少的关键对象)
	graph, err := entc.LoadGraph(schemaPath, cfg)
	if err != nil {
		log.Fatalf("加载 Graph 失败: %v", err)
	}

	// 执行核心 Ent 代码生成
	opts := []entc.Option{
		entc.TemplateFiles(
			// "./internal/ent/template/debug.tmpl",
			// "./internal/ent/template/stringer.tmpl",
			"./internal/ent/template/aggregate.tmpl",
			"./internal/ent/template/order_by.tmpl",
			"./internal/ent/template/order_field_by.tmpl",
			"./internal/ent/template/pagination.tmpl",
			"./internal/ent/template/to_map.tmpl",
			"./internal/ent/template/query_gorm_compat.tmpl",
			"./internal/ent/template/where_if.tmpl",
			"./internal/ent/template/order_if.tmpl",
			"./internal/ent/template/json_query.tmpl",
		),
	}
	if err := entc.Generate(schemaPath, graph.Config, opts...); err != nil {
		log.Fatalf("代码生成错误: %v", err)
	}
	fmt.Println("Ent 核心代码生成成功")

	// 手动渲染审计模板
	auditTmpl, err := gen.NewTemplate("audit").ParseFiles("./internal/ent/template/audit.tmpl")
	if err != nil {
		log.Fatalf("解析模板失败: %v", err)
	}

	_ = os.MkdirAll(outputHookDir, 0755)
	f, err := os.Create(filepath.Join(outputHookDir, "audit_gen.go"))
	if err != nil {
		log.Fatalf("创建文件失败: %v", err)
	}
	defer f.Close()

	if err := auditTmpl.ExecuteTemplate(f, "audit_hooks", graph); err != nil {
		log.Fatalf("渲染失败: %v", err)
	}
}

